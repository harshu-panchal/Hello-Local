/**
 * Helper to check if a main navigation item is currently active
 */
export function isNavItemActive(currentPath: string, targetPath: string): boolean {
  if (targetPath === '/seller') {
    return currentPath === '/seller' || currentPath === '/seller/';
  }
  return currentPath === targetPath || currentPath.startsWith(targetPath + '/');
}

/**
 * Helper to check if any submenu item is currently active
 */
export function isSubmenuActive(currentPath: string, submenuItems?: SellerSubNavItem[]): boolean {
  if (!submenuItems || submenuItems.length === 0) return false;
  return submenuItems.some(item =>
    currentPath === item.path || currentPath.startsWith(item.path + '/')
  );
}
